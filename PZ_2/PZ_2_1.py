#Вариант 24.С начала суток прошло N секунд(N-целое).Найти колличество полных минут,прошедших с наччала суток.

while True:
    try:
        n = int(input("Введите количество секунд: "))

    except ValueError:
        print("Ошибка: Введите целое число")
        exit()

    print(n // 60, "вот столько минут прошло")

